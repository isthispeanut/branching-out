export function normalizeAnswer(answer) {
  const normalized = answer
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9+#]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/^(a|an|the)\s+/, '');

  return normalized
    .split(' ')
    .map((word) => {
      if (irregularPlurals.has(word)) return irregularPlurals.get(word);
      if (unchangedSWords.has(word)) return word;
      if (word.length > 4 && word.endsWith('ies')) return `${word.slice(0, -3)}y`;
      if (
        word.length > 4 &&
        /(ches|shes|sses|xes|zes)$/.test(word)
      ) {
        return word.slice(0, -2);
      }
      if (word.length > 3 && word.endsWith('s') && !/(ss|us|is)$/.test(word)) {
        return word.slice(0, -1);
      }
      return word;
    })
    .join(' ');
}

function isOneCharacterTypo(first, second) {
  if (first === second || Math.abs(first.length - second.length) > 1) return false;
  if (Math.min(first.length, second.length) < 5) return false;

  let firstIndex = 0;
  let secondIndex = 0;
  let edits = 0;

  while (firstIndex < first.length && secondIndex < second.length) {
    if (first[firstIndex] === second[secondIndex]) {
      firstIndex += 1;
      secondIndex += 1;
      continue;
    }

    edits += 1;
    if (edits > 1) return false;
    if (
      first.length === second.length &&
      first[firstIndex] === second[secondIndex + 1] &&
      first[firstIndex + 1] === second[secondIndex] &&
      first.slice(firstIndex + 2) === second.slice(secondIndex + 2)
    ) {
      return true;
    }
    if (first.length > second.length) firstIndex += 1;
    else if (second.length > first.length) secondIndex += 1;
    else {
      firstIndex += 1;
      secondIndex += 1;
    }
  }

  if (firstIndex < first.length || secondIndex < second.length) edits += 1;
  return edits === 1;
}

export function findAcceptedAnswer(question, response) {
  const normalizedResponse = normalizeAnswer(response);
  if (!normalizedResponse) return undefined;

  const candidates = question.answers.map((answer) => ({
    answer,
    names: [answer.text, ...(answer.aliases ?? [])].map(normalizeAnswer),
  }));
  const exactMatch = candidates.find(({ names }) => names.includes(normalizedResponse));
  if (exactMatch) return exactMatch.answer;

  const closeMatches = candidates.filter(({ names }) =>
    names.some((name) => isOneCharacterTypo(normalizedResponse, name)),
  );
  return closeMatches.length === 1 ? closeMatches[0].answer : undefined;
}

export function getRarity(points) {
  if (points >= 80) return 'VERY RARE';
  if (points >= 50) return 'RARE';
  if (points >= 25) return 'UNCOMMON';
  return 'COMMON';
}

export function getTodayDate(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function createSeededRandom(seedText) {
  let seed = 2166136261;
  for (let index = 0; index < seedText.length; index += 1) {
    seed ^= seedText.charCodeAt(index);
    seed = Math.imul(seed, 16777619);
  }

  return function random() {
    seed += 0x6d2b79f5;
    let value = seed;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

