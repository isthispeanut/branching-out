export function normalizeAnswer(answer) {
  return answer
    .normalize('NFKC')
    .trim()
    .replace(/\s+/g, ' ')
    .toLocaleLowerCase();
}

export function findAcceptedAnswer(question, response) {
  const normalizedResponse = normalizeAnswer(response);
  if (!normalizedResponse) return undefined;

  return question.answers.find((answer) =>
    [answer.text, ...(answer.aliases ?? [])].some(
      (candidate) => normalizeAnswer(candidate) === normalizedResponse,
    ),
  );
}

export function getRarity(points) {
  if (points >= 80) return 'VERY RARE';
  if (points >= 50) return 'RARE';
  if (points >= 25) return 'UNCOMMON';
  return 'COMMON';
}

export function getTodayDate(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, '0');
  const day = String(date.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

function createSeededRandom(seedText) {
  let seed = 2166136261;
  for (let index = 0; index < seedText.length; index += 1) {
    seed ^= seedText.charCodeAt(index);
    seed = Math.imul(seed, 16777619);
  }

  return function random() {
    seed += 0x6d2b79f5;
    let value = seed;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

export function getDailyQuestions(date = getTodayDate()) {
  const random = createSeededRandom(date);
  const shuffled = [...questions];

  for (let index = shuffled.length - 1; index > 0; index -= 1) {
    const swapIndex = Math.floor(random() * (index + 1));
    [shuffled[index], shuffled[swapIndex]] = [shuffled[swapIndex], shuffled[index]];
  }

  return shuffled.slice(0, 7);
}
